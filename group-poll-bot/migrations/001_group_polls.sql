CREATE TABLE IF NOT EXISTS group_poll_bot.webhook_events (
  event_id TEXT PRIMARY KEY,
  event_type TEXT NOT NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS group_poll_bot.polls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id TEXT NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
  going_count INTEGER NOT NULL DEFAULT 0 CHECK (going_count >= 0),
  not_going_count INTEGER NOT NULL DEFAULT 0 CHECK (not_going_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_group_poll_bot_one_open_per_group
  ON group_poll_bot.polls (group_id)
  WHERE status = 'OPEN';

CREATE TABLE IF NOT EXISTS group_poll_bot.votes (
  poll_id BIGINT NOT NULL REFERENCES group_poll_bot.polls(id) ON DELETE CASCADE,
  line_user_id TEXT NOT NULL,
  choice SMALLINT NOT NULL CHECK (choice IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (poll_id, line_user_id)
);
