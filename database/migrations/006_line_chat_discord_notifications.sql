CREATE TABLE IF NOT EXISTS line_chat_discord_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id TEXT NOT NULL UNIQUE REFERENCES webhook_events(event_id),
  conversation_id BIGINT NOT NULL REFERENCES conversations(id),
  message_id BIGINT NOT NULL REFERENCES messages(id),
  discord_payload JSONB,
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_line_chat_discord_notifications_due
  ON line_chat_discord_notifications (next_attempt_at, id)
  WHERE status = 'PENDING';
