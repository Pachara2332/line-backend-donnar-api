CREATE TABLE IF NOT EXISTS messenger_users (
  messenger_user_id TEXT PRIMARY KEY,
  display_name TEXT,
  picture_url TEXT,
  profile_synced_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE conversations ADD COLUMN IF NOT EXISTS channel TEXT NOT NULL DEFAULT 'LINE';
ALTER TABLE conversations ADD COLUMN IF NOT EXISTS messenger_user_id TEXT REFERENCES messenger_users(messenger_user_id);
ALTER TABLE conversations ALTER COLUMN line_user_id DROP NOT NULL;
ALTER TABLE conversations ADD CONSTRAINT conversations_channel_check CHECK (channel IN ('LINE', 'FACEBOOK'));
ALTER TABLE conversations ADD CONSTRAINT conversations_channel_identity_check CHECK (
  (channel = 'LINE' AND line_user_id IS NOT NULL AND messenger_user_id IS NULL) OR
  (channel = 'FACEBOOK' AND line_user_id IS NULL AND messenger_user_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_conversations_messenger_user ON conversations(messenger_user_id) WHERE messenger_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_conversations_channel_updated ON conversations(channel, updated_at DESC, id DESC);

ALTER TABLE messages ADD COLUMN IF NOT EXISTS provider_timestamp TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS messenger_menu_publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_json JSONB NOT NULL,
  page_menu_id TEXT,
  status TEXT NOT NULL CHECK (status IN ('DRAFT', 'CREATING', 'PUBLISHED', 'FAILED', 'REPLACED')),
  last_error TEXT,
  created_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_messenger_menu_single_draft ON messenger_menu_publications(status) WHERE status = 'DRAFT';
CREATE UNIQUE INDEX IF NOT EXISTS idx_messenger_menu_single_creation ON messenger_menu_publications((status)) WHERE status = 'CREATING';
