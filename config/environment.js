function loadConfig(env = process.env) {
  const nodeEnv = env.NODE_ENV || 'development';
  if (nodeEnv === 'production' && !env.DATABASE_URL) {
    throw new Error('Production requires DATABASE_URL');
  }
  if (env.DATABASE_URL && !/^postgres(?:ql)?:\/\//i.test(env.DATABASE_URL)) {
    throw new Error('DATABASE_URL must be a PostgreSQL connection string');
  }
  if (nodeEnv === 'production' && (!env.LINE_CHANNEL_SECRET || !env.LINE_CHANNEL_ACCESS_TOKEN || !env.STAFF_PASSWORD_HASH)) {
    throw new Error('Production requires LINE_CHANNEL_SECRET, LINE_CHANNEL_ACCESS_TOKEN, and STAFF_PASSWORD_HASH');
  }
  if (nodeEnv === 'production' && !/^scrypt\$[a-f0-9]{32}\$[a-f0-9]{128}$/i.test(env.STAFF_PASSWORD_HASH || '')) {
    throw new Error('STAFF_PASSWORD_HASH must be generated by scripts/hash-password.js');
  }
  if (env.LIFF_ID && !/^\d+-[A-Za-z0-9]+$/.test(env.LIFF_ID)) throw new Error('LIFF_ID must look like 1234567890-AbCdEfGh');
  if (env.SELLER_TAX_ID && !/^\d{13}$/.test(env.SELLER_TAX_ID)) throw new Error('SELLER_TAX_ID must be 13 digits');
  if (env.SELLER_BRANCH_CODE && !/^\d{5}$/.test(env.SELLER_BRANCH_CODE)) throw new Error('SELLER_BRANCH_CODE must be 5 digits');
  if (env.MESSENGER_GRAPH_API_VERSION && !/^v\d+\.\d+$/.test(env.MESSENGER_GRAPH_API_VERSION)) throw new Error('MESSENGER_GRAPH_API_VERSION must look like v26.0');
  const port = Number(env.PORT || 3000);
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('PORT must be an integer from 1 to 65535');

  return {
    nodeEnv,
    isProduction: nodeEnv === 'production',
    port,
    databaseUrl: env.DATABASE_URL || '',
    lineChannelSecret: env.LINE_CHANNEL_SECRET || '',
    lineAccessToken: env.LINE_CHANNEL_ACCESS_TOKEN || '',
    messengerAppSecret: env.MESSENGER_APP_SECRET || '',
    messengerWebhookVerifyToken: env.MESSENGER_WEBHOOK_VERIFY_TOKEN || '',
    messengerPageAccessToken: env.MESSENGER_PAGE_ACCESS_TOKEN || '',
    messengerPageId: env.MESSENGER_PAGE_ID || '',
    messengerGraphApiVersion: env.MESSENGER_GRAPH_API_VERSION || '',
    messengerEnabled: Boolean(env.MESSENGER_APP_SECRET && env.MESSENGER_WEBHOOK_VERIFY_TOKEN && env.MESSENGER_PAGE_ACCESS_TOKEN && env.MESSENGER_PAGE_ID && env.MESSENGER_GRAPH_API_VERSION),
    resendApiKey: env.RESEND_API_KEY || '',
    resendFromEmail: env.RESEND_FROM_EMAIL || '',
    chatNotificationEmail: env.CHAT_NOTIFICATION_EMAIL || 'mrtgamer76@gmail.com',
    emailNotificationsEnabled: Boolean(env.RESEND_API_KEY && env.RESEND_FROM_EMAIL),
    discordBotToken: env.DISCORD_BOT_TOKEN || '',
    discordChannelId: env.DISCORD_CHANNEL_ID || '',
    discordNotificationsEnabled: Boolean(env.DISCORD_BOT_TOKEN && env.DISCORD_CHANNEL_ID),
    staffUsername: env.STAFF_USERNAME || 'admin',
    staffPasswordHash: env.STAFF_PASSWORD_HASH || '',
    fakeLineMode: env.LINE_FAKE_MODE === 'true' && nodeEnv !== 'production',
    publicBaseUrl: env.PUBLIC_BASE_URL || 'http://localhost:3000',
    liffId: env.LIFF_ID || '',
    seller: {
      name: env.SELLER_NAME || '',
      taxId: env.SELLER_TAX_ID || '',
      branchCode: env.SELLER_BRANCH_CODE || '',
      address: (env.SELLER_ADDRESS || '').replace(/\\n/g, '\n'),
      phone: env.SELLER_PHONE || '',
      email: env.SELLER_EMAIL || '',
      website: env.SELLER_WEBSITE || '',
      bankAccount: (env.SELLER_BANK_ACCOUNT || '').replace(/\\n/g, '\n'),
      vatRegistered: env.SELLER_VAT_REGISTERED === 'true',
    },
    richMenuImagePath: env.RICH_MENU_IMAGE_PATH || pathFromRepo('assets/line-rich-menu-2500x1686.jpg'),
  };
}

function pathFromRepo(relativePath) {
  return require('node:path').resolve(__dirname, '..', relativePath);
}

module.exports = { loadConfig };
